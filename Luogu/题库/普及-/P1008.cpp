#include <bits/stdc++.h>
using namespace std;

int main() {
    int b,c;
    for (int a=123;a<=333;++a) {
        b=a*2;
        c=a*3;
        if (a/100+a%100/10+a%100%10+
        b/100+b%100/10+b%100%10+
        c/100+c%100/10+c%100%10==1+2+3+4+5+6+7+8+9 && 
        (a/100)*(a%100/10)*(a%100%10)*
        (b/100)*(b%100/10)*(b%100%10)*
        (c/100)*(c%100/10)*(c%100%10)==1*2*3*4*5*6*7*8*9) {
            printf("%d %d %d\n",a,b,c);
        }
    }
    return 0;
}