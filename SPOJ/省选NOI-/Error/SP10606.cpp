                f[i][5][_0][_1][_2][_3][_4][_5^1][_6][_7][_8][_9]+=f[i-1][p][_0][_1][_2][_3][_4][_5][_6][_7][_8][_9];
                f[i][6][_0][_1][_2][_3][_4][_5][_6^1][_7][_8][_9]+=f[i-1][p][_0][_1][_2][_3][_4][_5][_6][_7][_8][_9];
